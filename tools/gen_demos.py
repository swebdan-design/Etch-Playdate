#!/usr/bin/env python3
"""
ETCH CRANK -- by Synth Centric
Copies ETCH's eight ROM tracks (the album) into platform/demos.c, byte for
byte, from an ETCH (Etch---GB) checkout's src/presets/preset_data.c and
track_names.c (both generated there by ETCH's tools/presets.py).  The data is
project_t's header (73 bytes, up to .pat), a pattern count, then the patterns;
demos_load() expands it exactly as ETCH's preset_load() does.

    python3 tools/gen_demos.py /path/to/Etch---GB
"""
import hashlib, os, re, subprocess, sys

src = sys.argv[1]
data = open(os.path.join(src, "src/presets/preset_data.c")).read()
names = re.findall(r"^\s+\"([^\"]+)\",", open(os.path.join(src, "src/presets/track_names.c")).read(), re.M)
tracks = re.findall(r"static const uint8_t (trk\d)\[(\d+)\] = \{(.*?)\};", data, re.S)
assert len(tracks) == 8 and len(names) == 8
commit = subprocess.run(["git", "-C", src, "rev-parse", "--short", "HEAD"], capture_output=True, text=True).stdout.strip()
out = ["/* ETCH CRANK -- generated by tools/gen_demos.py from ETCH @ %s; do not edit. */" % commit,
       "/* ETCH's eight ROM tracks, byte for byte (src/presets/preset_data.c). */",
       '#include <string.h>', '#include "demos.h"', "",
       "/* ETCH's header is project_t up to .pat: 73 bytes on the Game Boy, where nothing is padded.",
       " * Here .pat is aligned to 2 (offset 74); the 73 bytes before it are laid out the same. */",
       "typedef char hdr_check[(offsetof(project_t, start_pattern) == 72 && sizeof(pattern_t) == 64) ? 1 : -1];", ""]
digest = hashlib.sha256()
for name, n, body in tracks:
    vals = [int(v, 16) for v in re.findall(r"0x([0-9A-Fa-f]{2})", body)]
    assert len(vals) == int(n)
    digest.update(bytes(vals))
    out.append("static const uint8_t %s[%s] = {" % (name, n))
    for i in range(0, len(vals), 16):
        out.append("    " + ",".join("0x%02X" % v for v in vals[i:i + 16]) + ",")
    out.append("};")
out.append("static const uint8_t *const tracks[DEMO_COUNT] = { trk0, trk1, trk2, trk3, trk4, trk5, trk6, trk7 };")
out.append("const char *const demo_names[DEMO_COUNT] = { %s };" % ", ".join('"%s"' % n for n in names))
out.append('''
/* ETCH's preset_load(), into p */
void demos_load(uint8_t t, project_t *p)
{
    const uint8_t *d = tracks[t & 7];
    uint8_t i, n;
    memcpy(p, d, 73);
    n = d[73];
    d += 74;
    for (i = 0; i < NUM_PATTERNS; i++) {
        if (i < n) memcpy(&p->pat[i], d + (uint16_t)i * 64, 64);
        else pattern_clear(&p->pat[i]);
    }
    project_drum_defaults(p);
}''')
open("platform/demos.c", "w").write("\n".join(out) + "\n")
print("platform/demos.c: 8 tracks from ETCH @", commit, "sha256 of the data", digest.hexdigest()[:16])
